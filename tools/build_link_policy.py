"""Generate the browser connection policy from the literal config owner."""
from __future__ import annotations

import argparse
import ast
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def source():
    tree = ast.parse((ROOT / 'rover/config.py').read_text(encoding='utf-8-sig'))
    for node in tree.body:
        if isinstance(node, ast.Assign) and any(
                isinstance(target, ast.Name) and target.id == 'STATION_LINK_WATCHDOG'
                for target in node.targets):
            policy = ast.literal_eval(node.value)
            if not isinstance(policy, dict) or any(
                    type(value) is not int or value <= 0 for value in policy.values()):
                raise ValueError('Invalid browser connection policy')
            return ('// Generated by tools/build_link_policy.py from rover/config.py.\n'
                    '// Edit the configuration owner, then regenerate this file.\n'
                    'export const STATION_LINK_WATCHDOG = Object.freeze('
                    + json.dumps(policy, indent=2) + ');\n')
    raise ValueError('STATION_LINK_WATCHDOG is missing')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    path = ROOT / 'station/web/link_policy.js'
    expected = source()
    if args.check:
        if not path.is_file() or path.read_text(encoding='utf-8') != expected:
            raise SystemExit('Browser link policy must be regenerated')
        print('Browser link policy matches config.py')
    else:
        path.write_text(expected, encoding='utf-8')
        print(path)
