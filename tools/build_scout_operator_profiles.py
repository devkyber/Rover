"""Generate laptop Scout source profiles from config.py; never opens hardware."""
import argparse
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'rover'))
import config

OUTPUT = ROOT / 'station/web/scout_profiles.js'


def render():
    return ('// Generated by tools/build_scout_operator_profiles.py from rover/config.py.\n'
            '// Original source settings; not measured mechanism calibration.\n'
            'export const JUMPER_OPERATOR_PROFILES = ' +
            json.dumps(config.JUMPER_OPERATOR_PROFILES, ensure_ascii=True,
                       allow_nan=False, indent=2) + ';\n'
            f'export const SCOUT_PLOT_IMPORT_MAX_BYTES = {config.SCOUT_REPORT_MAX_IMPORT_BYTES};\n')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    expected = render()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding='utf-8') != expected:
            raise SystemExit('Scout operator profiles stale: run python tools/build_scout_operator_profiles.py')
        print('Scout operator profiles match config.py')
    else:
        with OUTPUT.open('w', encoding='utf-8', newline='\n') as stream:
            stream.write(expected)
        print('Generated station/web/scout_profiles.js')


if __name__ == '__main__':
    main()
